let observer: MutationObserver | null = null;
const originalText = new WeakMap<Node, string>();
const originalAttrs = new WeakMap<Element, Map<string, string>>();
const ATTRS = ["title", "aria-label", "placeholder", "alt"];

export function getLocale(): AppLocale {
  const value = localStorage.getItem(STORAGE_KEY);
  return APP_LOCALES.includes(value as AppLocale) ? value as AppLocale : "en";
}

export function saveLocale(locale: AppLocale): void {
  localStorage.setItem(STORAGE_KEY, locale);
}

export function setLocale(locale: AppLocale): void {
  saveLocale(locale);
  window.location.reload();
}

export function tr(value: string, locale: AppLocale = getLocale()): string {
  if (locale === "en") return value;
  const trimmed = value.trim();
  const dict = locale === "hr" ? HR : OTHER[locale];
  const translated = dict?.[trimmed];
  return translated ? value.replace(trimmed, translated) : value;
}

function translateString(value: string, locale: AppLocale): string {
  return tr(value, locale);
}

function visit(node: Node, locale: AppLocale): void {
  if (node.nodeType === Node.TEXT_NODE) {
    const value = node.nodeValue;
    if (!value || !value.trim() || node.parentElement?.closest("code, pre")) return;
    if (!originalText.has(node)) originalText.set(node, value);
    const base = originalText.get(node) ?? value;
    const next = translateString(base, locale);
    if (node.nodeValue !== next) node.nodeValue = next;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  const el = node as Element;
  if (["SCRIPT", "STYLE", "CODE", "PRE"].includes(el.tagName)) return;
  let attrMap = originalAttrs.get(el);
  if (!attrMap) {
    attrMap = new Map<string, string>();
    originalAttrs.set(el, attrMap);
  }
  for (const attr of ATTRS) {
    const current = el.getAttribute(attr);
    if (!current) continue;
    if (!attrMap.has(attr)) attrMap.set(attr, current);
    const base = attrMap.get(attr) ?? current;
    const next = translateString(base, locale);
    if (current !== next) el.setAttribute(attr, next);
  }
  for (const child of Array.from(el.childNodes)) visit(child, locale);
}

export function startLocalization(): void {
  const locale = getLocale();
  document.documentElement.lang = locale;
  document.documentElement.dataset.ghostftpLocale = locale;
  if (locale === "en") return;
  visit(document.body, locale);
  observer?.disconnect();
  observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData") visit(record.target, locale);
      for (const node of Array.from(record.addedNodes)) visit(node, locale);
      if (record.type === "attributes") visit(record.target, locale);
    }
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ATTRS,
  });
}
